package basics;

public class VariablesDemo {

    public static void main(String[] args) {

        // 🔹 Variable declarations
        int a = 10;
        int b = 20;

        // 🔹 Addition
        int sum = a + b;

        // 🔹 Output
        System.out.println("Sum = " + sum);
    }
}
